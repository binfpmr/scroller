const Glyph& Find(char c) {
  if (c >= 'a' && c <= 'z') {
    c = static_cast<char>(c - 'a' + 'A');
  }
  for (const Glyph& g : kGlyphs) {
    if (g.c == c) {
      return g;
    }
  }
  return kGlyphs[sizeof(kGlyphs) / sizeof(kGlyphs[0]) - 1];  // '?'
}

void DrawGlyph(Surface& s, int x, int y, const Glyph& g, Color color) {
  for (int row = 0; row < kGlyphHeight; ++row) {
    const int py = y + row;
    if (py < 0 || py >= s.height) {
      continue;
    }
    for (int col = 0; col < kGlyphWidth; ++col) {
      const int px = x + col;
      if (px >= 0 && px < s.width && (g.rows[row] & (0x10 >> col)) != 0) {
        s.Row(py)[px] = color;
      }
    }
  }
}

