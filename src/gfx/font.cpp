void DrawText(Surface& s, int x, int y, const char* text, Color color) {
  int cx = x;
  for (const char* p = text; *p != '\0'; ++p) {
    if (*p == '\n') {
      cx = x;
      y += kLineHeight;
      continue;
    }
    DrawGlyph(s, cx, y, Find(*p), color);
    cx += kCharAdvance;
  }
}

int TextWidth(const char* text) {
  int widest = 0;
  int chars = 0;
  for (const char* p = text;; ++p) {
    if (*p == '\n' || *p == '\0') {
      const int width = chars > 0 ? chars * kCharAdvance - 1 : 0;
      widest = width > widest ? width : widest;
      chars = 0;
      if (*p == '\0') {
        break;
      }
      continue;
    }
    ++chars;
  }
  return widest;
}

