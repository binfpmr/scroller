#!/usr/bin/env python3
"""Write a header with the git version of the source tree: version_header.py <repo> <output.h>

Defines kScrollerVersion, e.g. "ca7acfc" or "ca7acfc-dirty". Rewrites the file only when the text changes, so
running it on every build only recompiles what includes it after a commit or an edit.
"""

import subprocess
import sys
from pathlib import Path


def main() -> int:
    repo, out = Path(sys.argv[1]), Path(sys.argv[2])
    try:
        version = subprocess.run(["git", "-C", str(repo), "describe", "--always", "--dirty", "--abbrev=7"],
                                 capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        version = "unknown"
    text = ("// Generated by tools/version_header.py. Do not edit.\n#pragma once\n\n"
            f'inline constexpr char kScrollerVersion[] = "{version}";\n')
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
